function renderLineChart(container, points, title, yLabel, color = "#6366f1") {
  if (points.length === 0) {
    container.createEl("p", { text: "No data yet.", cls: "wt-empty-msg" });
    return;
  }
  const plotPoints = aggregatePoints(points, 40);
  const chartDiv = container.createDiv({ cls: "wt-chart" });
  chartDiv.createEl("div", { text: title, cls: "wt-chart-title" });
  const W = 320, H = 180, PL = 45, PR = 10, PT = 10, PB = 40;
  const pW = W - PL - PR, pH = H - PT - PB;
  const vals = plotPoints.map((p) => p.value);
  const maxV = Math.max(...vals, 1), minV = Math.min(...vals, 0), range = maxV - minV || 1;
  const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", `0 0 ${W} ${H}`);
  svg.setAttribute("class", "wt-svg-chart");
  for (let i = 0; i <= 4; i++) {
    const y = PT + pH / 4 * i;
    const gl = document.createElementNS("http://www.w3.org/2000/svg", "line");
    gl.setAttribute("x1", String(PL));
    gl.setAttribute("x2", String(W - PR));
    gl.setAttribute("y1", String(y));
    gl.setAttribute("y2", String(y));
    gl.setAttribute("class", "wt-grid-line");
    svg.appendChild(gl);
    const lb = document.createElementNS("http://www.w3.org/2000/svg", "text");
    lb.setAttribute("x", String(PL - 5));
    lb.setAttribute("y", String(y + 4));
    lb.setAttribute("class", "wt-axis-label");
    lb.setAttribute("text-anchor", "end");
    const v = maxV - range / 4 * i;
    lb.textContent = v >= 1e3 ? `${(v / 1e3).toFixed(1)}k` : String(Math.round(v));
    svg.appendChild(lb);
  }
  const yl = document.createElementNS("http://www.w3.org/2000/svg", "text");
  yl.setAttribute("x", "12");
  yl.setAttribute("y", String(PT + pH / 2));
  yl.setAttribute("class", "wt-axis-title");
  yl.setAttribute("transform", `rotate(-90, 12, ${PT + pH / 2})`);
  yl.textContent = yLabel;
  svg.appendChild(yl);
  const xStep = plotPoints.length > 1 ? pW / (plotPoints.length - 1) : pW / 2;
  const coords = plotPoints.map((p, i) => ({
    x: PL + (plotPoints.length > 1 ? i * xStep : pW / 2),
    y: PT + pH - (p.value - minV) / range * pH
  }));
  if (coords.length > 1) {
    const d = coords.map((c, i) => `${i === 0 ? "M" : "L"}${c.x},${c.y}`).join(" ");
    const path = document.createElementNS("http://www.w3.org/2000/svg", "path");
    path.setAttribute("d", d);
    path.setAttribute("fill", "none");
    path.setAttribute("stroke", color);
    path.setAttribute("stroke-width", "2");
    path.setAttribute("stroke-linejoin", "round");
    svg.appendChild(path);
  }
  const maxLb = 8, lEvery = Math.max(1, Math.ceil(plotPoints.length / maxLb));
  coords.forEach((c, i) => {
    const ci = document.createElementNS("http://www.w3.org/2000/svg", "circle");
    ci.setAttribute("cx", String(c.x));
    ci.setAttribute("cy", String(c.y));
    ci.setAttribute("r", "3");
    ci.setAttribute("fill", color);
    const tt = document.createElementNS("http://www.w3.org/2000/svg", "title");
    tt.textContent = `${plotPoints[i].label}: ${plotPoints[i].value}`;
    ci.appendChild(tt);
    svg.appendChild(ci);
    if (i % lEvery === 0 || i === plotPoints.length - 1) {
      const xl = document.createElementNS("http://www.w3.org/2000/svg", "text");
      xl.setAttribute("x", String(c.x));
      xl.setAttribute("y", String(H - 5));
      xl.setAttribute("class", "wt-axis-label");
      xl.setAttribute("text-anchor", "middle");
      xl.textContent = plotPoints[i].label;
      svg.appendChild(xl);
    }
  });
  chartDiv.appendChild(svg);
}
